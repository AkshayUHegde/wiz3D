# Regenerates vk_forwards.asm, vk_forward_names.h and vulkan-1.def from the
# export table of the system vulkan-1.dll. Games link the full export set
# (Doom 2016 imports vkBindBufferMemory etc. directly), so the proxy must
# re-export everything the real loader does. Six entry points stay hand-written
# in dllmain.cpp; the rest become x64 jump trampolines through a lazily filled
# table.
param([string]$Dumpbin = (Get-ChildItem "C:\Program Files\Microsoft Visual Studio\*\*\VC\Tools\MSVC\*\bin\Hostx64\x64\dumpbin.exe" | Select-Object -First 1).FullName)

$handWritten = @('vkGetInstanceProcAddr','vkCreateInstance','vkEnumerateInstanceExtensionProperties',
                 'vkEnumerateInstanceLayerProperties','vkEnumerateInstanceVersion','vkGetDeviceProcAddr')

$out = & $Dumpbin /exports "$env:SystemRoot\System32\vulkan-1.dll"
$all = $out | Where-Object { $_ -match '^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)' } | ForEach-Object { $Matches[1] } | Sort-Object
$fwd = $all | Where-Object { $handWritten -notcontains $_ }

$asm = New-Object System.Text.StringBuilder
[void]$asm.AppendLine("; Generated by gen_forwards.ps1 - do not edit. x64 only.")
[void]$asm.AppendLine("EXTERN g_vkForward:QWORD")
[void]$asm.AppendLine("EXTERN wiz3D_ResolveForward:PROC")
[void]$asm.AppendLine(".code")
[void]$asm.AppendLine("")
[void]$asm.AppendLine("; Slow path: resolve slot ecx, preserving the four GPR/XMM argument registers.")
[void]$asm.AppendLine("vk_resolve_and_jump PROC PRIVATE")
[void]$asm.AppendLine("    push rcx")
[void]$asm.AppendLine("    push rdx")
[void]$asm.AppendLine("    push r8")
[void]$asm.AppendLine("    push r9")
[void]$asm.AppendLine("    sub rsp, 68h")
[void]$asm.AppendLine("    movdqu [rsp+20h], xmm0")
[void]$asm.AppendLine("    movdqu [rsp+30h], xmm1")
[void]$asm.AppendLine("    movdqu [rsp+40h], xmm2")
[void]$asm.AppendLine("    movdqu [rsp+50h], xmm3")
[void]$asm.AppendLine("    mov ecx, eax")
[void]$asm.AppendLine("    call wiz3D_ResolveForward")
[void]$asm.AppendLine("    movdqu xmm0, [rsp+20h]")
[void]$asm.AppendLine("    movdqu xmm1, [rsp+30h]")
[void]$asm.AppendLine("    movdqu xmm2, [rsp+40h]")
[void]$asm.AppendLine("    movdqu xmm3, [rsp+50h]")
[void]$asm.AppendLine("    add rsp, 68h")
[void]$asm.AppendLine("    pop r9")
[void]$asm.AppendLine("    pop r8")
[void]$asm.AppendLine("    pop rdx")
[void]$asm.AppendLine("    pop rcx")
[void]$asm.AppendLine("    jmp rax")
[void]$asm.AppendLine("vk_resolve_and_jump ENDP")
[void]$asm.AppendLine("")
$i = 0
foreach ($n in $fwd) {
    [void]$asm.AppendLine("$n PROC")
    [void]$asm.AppendLine("    mov rax, QWORD PTR [g_vkForward + $($i*8)]")
    [void]$asm.AppendLine("    test rax, rax")
    [void]$asm.AppendLine("    jz @F")
    [void]$asm.AppendLine("    jmp rax")
    [void]$asm.AppendLine("@@: mov eax, $i")
    [void]$asm.AppendLine("    jmp vk_resolve_and_jump")
    [void]$asm.AppendLine("$n ENDP")
    $i++
}
[void]$asm.AppendLine("END")
[IO.File]::WriteAllText("$PSScriptRoot\vk_forwards.asm", $asm.ToString())

$h = "// Generated by gen_forwards.ps1 - do not edit.`r`n#define WIZ3D_VK_FORWARD_COUNT $($fwd.Count)`r`nstatic const char* const g_vkForwardNames[WIZ3D_VK_FORWARD_COUNT] = {`r`n"
$h += ($fwd | ForEach-Object { "    `"$_`"," }) -join "`r`n"
$h += "`r`n};`r`n"
[IO.File]::WriteAllText("$PSScriptRoot\vk_forward_names.h", $h)

$def = "LIBRARY vulkan-1`r`nEXPORTS`r`n"
$ord = 1
foreach ($n in ($handWritten + $fwd)) { $def += "    $n @$ord`r`n"; $ord++ }
[IO.File]::WriteAllText("$PSScriptRoot\vulkan-1.def", $def)

"exports: $($all.Count) total, $($fwd.Count) trampolines"
